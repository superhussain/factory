// Builds the dashboard's home-screen PNG icons with the Node standard library and writes
// worker/icons.js. `--check` regenerates them and fails on any byte difference.
import { readFile, writeFile } from "node:fs/promises";
import { crc32, deflateSync } from "node:zlib";

const target = new URL("../worker/icons.js", import.meta.url);

function chunk(type, data) {
  const head = Buffer.alloc(8);
  head.writeUInt32BE(data.length);
  head.write(type, 4, "latin1");
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])));
  return Buffer.concat([head, data, crc]);
}

function icon(size) {
  const r = Math.round;
  const bars = [0.22, 0.42, 0.62].map((x, i) => ({
    x0: r(x * size),
    x1: r(x * size) + r(0.16 * size),
    y0: r(0.25 * size),
    y1: r([0.75, 0.62, 0.5][i] * size),
  }));
  const rows = Buffer.alloc(size * (1 + size * 3));
  for (let y = 0; y < size; y++) {
    const row = y * (1 + size * 3);
    for (let x = 0; x < size; x++) {
      const white = bars.some((b) => x >= b.x0 && x < b.x1 && y >= b.y0 && y < b.y1);
      rows.set(white ? [0xff, 0xff, 0xff] : [0x7c, 0x3a, 0xed], row + 1 + x * 3);
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr.set([8, 2, 0, 0, 0], 8);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(rows, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const source =
  "// Generated by tools/icons.mjs. Do not edit.\n" +
  [
    ["ICON_192", 192],
    ["ICON_512", 512],
    ["APPLE_TOUCH_ICON", 180],
  ]
    .map(([name, size]) => `export const ${name} =\n  "${icon(size).toString("base64")}";\n`)
    .join("");

if (process.argv[2] === "--check") {
  if ((await readFile(target, "utf8")) !== source) {
    console.error("worker/icons.js is stale; run node tools/icons.mjs");
    process.exit(1);
  }
} else {
  await writeFile(target, source);
}
