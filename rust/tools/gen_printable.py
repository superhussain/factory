"""Write rust/factory/src/shared/unicode_printable.rs from this Python's str.isprintable.

python3 rust/tools/gen_printable.py
"""
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "factory/src/shared/unicode_printable.rs"


def main():
    ranges = []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF or chr(cp).isprintable():
            continue
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    lines = [f"// Generated by rust/tools/gen_printable.py from Python {sys.version.split()[0]}, "
             f"Unicode {unicodedata.unidata_version}. Do not edit.",
             "// Inclusive, sorted code point ranges where str.isprintable() is false.",
             "pub(crate) const NON_PRINTABLE: &[(u32, u32)] = &["]
    lines += [f"    (0x{a:X}, 0x{b:X})," for a, b in ranges]
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
