// Write rust/factory/src/shared/nfkc_table.rs: every code point whose one-character NFKC form
// differs, with that form, from the Unicode 12.1.0 UCD files in <ucd folder>.
//
// node rust/tools/gen_nfkc.mjs <ucd folder> [--check]
// --check exits 1 when the committed table differs from what the generator would write.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { MAX, loadUcd, nfkc, printable } from "./ucd.mjs";

const OUT = fileURLToPath(new URL("../factory/src/shared/nfkc_table.rs", import.meta.url));
const ucd = loadUcd(process.argv[2]);

const literal = (cps) =>
  '"' +
  cps
    .map((cp) => {
      const c = String.fromCodePoint(cp);
      return printable(ucd, cp) && c !== '"' && c !== "\\" ? c : `\\u{${cp.toString(16)}}`;
    })
    .join("") +
  '"';

const rows = [];
for (let cp = 0; cp <= MAX; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const folded = nfkc(ucd, [cp]);
  if (folded.length !== 1 || folded[0] !== cp)
    rows.push(`    (0x${cp.toString(16).toUpperCase()}, ${literal(folded)}),`);
}
const text =
  [
    "// Generated by rust/tools/gen_nfkc.mjs from the Unicode 12.1.0 UCD, as Python 3.8.10's tables. Do not edit.",
    "// Sorted code points whose one-character NFKC form differs, with that form.",
    "pub(crate) const NFKC: &[(u32, &str)] = &[",
    ...rows,
    "];",
  ].join("\n") + "\n";
if (process.argv[3] === "--check") process.exitCode = readFileSync(OUT, "utf8") === text ? 0 : 1;
else writeFileSync(OUT, text);
