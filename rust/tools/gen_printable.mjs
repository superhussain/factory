// Write rust/factory/src/shared/unicode_printable.rs: the ranges where Python's str.isprintable is
// false, from the Unicode 12.1.0 UCD files in <ucd folder>.
//
// node rust/tools/gen_printable.mjs <ucd folder>
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { MAX, loadUcd, printable } from "./ucd.mjs";

const OUT = fileURLToPath(new URL("../factory/src/shared/unicode_printable.rs", import.meta.url));
const ucd = loadUcd(process.argv[2]);
const ranges = [];
for (let cp = 0; cp <= MAX; cp++) {
  if ((cp >= 0xd800 && cp <= 0xdfff) || printable(ucd, cp)) continue;
  if (ranges.length && ranges.at(-1)[1] === cp - 1) ranges.at(-1)[1] = cp;
  else ranges.push([cp, cp]);
}
const hex = (n) => "0x" + n.toString(16).toUpperCase();
const lines = [
  "// Generated by rust/tools/gen_printable.mjs from the Unicode 12.1.0 UCD, as Python 3.8.10's tables. Do not edit.",
  "// Inclusive, sorted code point ranges where str.isprintable() is false.",
  "pub(crate) const NON_PRINTABLE: &[(u32, u32)] = &[",
  ...ranges.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`),
  "];",
];
writeFileSync(OUT, lines.join("\n") + "\n");
