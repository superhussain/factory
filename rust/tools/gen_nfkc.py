"""Write rust/factory/src/shared/nfkc_table.rs from this Python's unicodedata.normalize("NFKC", ch).

python3 rust/tools/gen_nfkc.py [--check]

--check exits 1 when the committed table differs from what this Python would write.
"""
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "factory/src/shared/nfkc_table.rs"


def literal(s):
    return '"' + "".join(c if c.isprintable() and c not in '"\\' else "\\u{%x}" % ord(c) for c in s) + '"'


def render():
    rows = []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        folded = unicodedata.normalize("NFKC", chr(cp))
        if folded != chr(cp):
            rows.append(f"    (0x{cp:X}, {literal(folded)}),")
    return "\n".join([
        f"// Generated by rust/tools/gen_nfkc.py from Python {sys.version.split()[0]}, "
        f"Unicode {unicodedata.unidata_version}. Do not edit.",
        "// Sorted code points whose one-character NFKC form differs, with that form.",
        "pub(crate) const NFKC: &[(u32, &str)] = &[",
        *rows,
        "];",
    ]) + "\n"


def main(argv):
    text = render()
    if argv == ["--check"]:
        return 0 if OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
